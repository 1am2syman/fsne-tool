"""Render a built sample page with the current template and its existing data.

Use this for template-only changes. Use ui/build.py when report data changes.
Completed live runs render directly from their frozen data through the server.
"""

import argparse
from pathlib import Path

from ui.render import extract_legacy, render

UI = Path(__file__).resolve().parent


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="sample page previously generated by ui/build.py")
    parser.add_argument("--html", type=Path, default=UI / "index.html")
    args = parser.parse_args()
    source = args.source.expanduser()
    html = source.read_text(encoding="utf-8")
    if "const RUN_ID = null;" not in html:
        raise SystemExit("Use the live server to render completed runs with their identity and frozen data")
    payload = extract_legacy(html)
    if not payload.get("STATUS", {}).get("labels"):
        raise SystemExit(f"{source}: no embedded report data")
    target = args.html.expanduser()
    target.write_text(render(payload), encoding="utf-8")
    print(f"rendered {target} with existing data from {source}")


if __name__ == "__main__":
    main()
